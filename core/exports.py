"""MOCK exports: a comparative statement (CSV) and an SAP-style purchase order (JSON + CSV).

Both are MOCKS. Mandi is not integrated with SAP or any ERP. The PO export only borrows the *shape* of the
header and item data a buyer keys into an ERP purchase order (in the style of SAP MM), so the deal that was agreed
in chat can be handed to the system of record without retyping. The field names and the SAP-style labels in
brackets are illustrative and UNVERIFIED: a procurement colleague should validate them against their own system.
Codes (purchasing organisation, group, plant, vendor numbers) come from config/scenario.yaml → po_export and are
fictional.

Pure functions: they take Mandi Core views (order_view, comparison) and return rows/dicts, so they are unit-tested.
"""
from __future__ import annotations

import csv
import io
from datetime import date
from typing import Any, Optional

MOCK_NOTE = ("MOCK export generated by Mandi. Not an SAP or ERP integration. Field names are illustrative and "
             "unverified; validate with your procurement team before use. All companies and prices are fictional.")

# (export key, human label, illustrative SAP MM-style label — UNVERIFIED)

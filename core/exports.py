def _rupees(paise: Optional[int]) -> str:
    if paise is None:
        return ""
    sign = "-" if paise < 0 else ""
    paise = abs(paise)
    return f"{sign}{paise // 100}.{paise % 100:02d}"


def _last_vendor_offer(offers: list[dict[str, Any]], vendor_id: str) -> Optional[dict[str, Any]]:
    mine = [x for x in offers if x["vendor_id"] == vendor_id and x["side"] == "VENDOR" and not x.get("redteam")]
    return mine[-1] if mine else None


# ----------------------------------------------------------------------------- comparative statement
STATEMENT_COLUMNS = ["rank", "vendor", "quote_ref", "valid_until", "quoted_unit_price", "price_basis",
                     "freight_per_unit", "landed_unit_price", "landed_total", "moq", "lead_time_days",
                     "payment_terms_days", "final_offer_unit_price", "final_offer_total", "status", "flags", "awarded"]


def comparative_statement(view: dict[str, Any], cmp: dict[str, Any]) -> dict[str, Any]:
    """The comparison form a buyer files with the award (in spirit, a price comparison list): one row per vendor
    with the quoted terms, the normalised landed cost, the traps found, the last negotiated offer, and the award."""
    o = view["order"]
    spec = o.get("spec") or {}
    quotes = {q["id"]: q for q in view["quotes"]}
    qty = cmp.get("quantity") or spec.get("quantity") or 0
    rows = []
    for r in cmp["rows"]:
        q = quotes.get(r["quote_id"], {})
        last = _last_vendor_offer(view["offers"], r["vendor_id"])
        status = "Disqualified" if r["vendor_status"] == "DISQUALIFIED" else (
            "Valid" if r["comparable"] else "Not comparable as quoted")
        rows.append({
            "rank": r["rank"] or "",
            "vendor": r["vendor"],
            "quote_ref": q.get("quote_ref", ""),
            "valid_until": r["valid_until"] or "",
            "quoted_unit_price": _rupees(r["unit_paise"]),
            "price_basis": (r["basis"] or "").replace("_", "-").lower(),
            "freight_per_unit": _rupees(r["freight_paise"]) if r["basis"] == "EX_WORKS" else "",
            "landed_unit_price": _rupees(r["landed_unit_paise"]),
            "landed_total": _rupees(r["landed_total_paise"]),
            "moq": r["moq"] or "",
            "lead_time_days": r["lead_time_days"] or "",
            "payment_terms_days": r["payment_terms_days"] or "",
            "final_offer_unit_price": _rupees(last["unit_price_paise"]) if last else "",
            "final_offer_total": _rupees(last["unit_price_paise"] * qty) if last and last["unit_price_paise"] else "",
            "status": status,
            "flags": "; ".join(r["flags"]),
            "awarded": "YES" if o.get("awarded_vendor_id") == r["vendor_id"] else "",
        })
    header = [
        ("Document", "Comparative statement (MOCK)"),
        ("Order / requisition", o["id"]),
        ("Buyer", o.get("buyer", "")),
        ("Plant", o.get("plant", "")),
        ("Item", spec.get("part_name", "")),
        ("Specification", spec.get("part_spec", "")),
        ("Drawing", spec.get("drawing_ref", "")),
        ("Quantity", f"{qty} {spec.get('uom', '')}".strip()),
        ("Needed by", spec.get("needed_by", "")),
        ("Currency", spec.get("currency", "INR") + " (prices exclude GST)"),
        ("Recommendation", cmp.get("recommendation", "")),
        ("Note", MOCK_NOTE),
    ]
    return {"header": header, "columns": STATEMENT_COLUMNS, "rows": rows}


def statement_csv(st: dict[str, Any]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    for k, v in st["header"]:
        w.writerow([k, v])
    w.writerow([])
    w.writerow(st["columns"])
    for r in st["rows"]:
        w.writerow([r[c] for c in st["columns"]])
    return buf.getvalue()


# ----------------------------------------------------------------------------- SAP-style PO
def po_export(view: dict[str, Any], cfg: dict[str, Any], *, document_date: date) -> dict[str, Any]:
    """Header + item data for the issued PO, in the shape of an ERP purchase order. Raises ValueError if no PO."""
    po = view.get("po")
    if not po:
        raise ValueError("No PO has been issued for this order yet.")
    o = view["order"]
    spec = o.get("spec") or {}
    vendor = next((v for v in view["vendors"] if v["vendor_id"] == po["vendor_id"]), {})
    price_unit = int(cfg.get("price_unit", 1))
    header = {
        "po_number": po["id"],
        "vendor_code": (cfg.get("vendor_codes") or {}).get(po["vendor_id"], po["vendor_id"]),
        "vendor_name": vendor.get("legal_name", po["vendor_id"]),
        "purchasing_org": cfg.get("purchasing_org", ""),
        "purchasing_group": cfg.get("purchasing_group", ""),
        "plant": cfg.get("plant_code", ""),
        "currency": spec.get("currency", "INR"),
        "document_date": document_date.isoformat(),
        "payment_terms_days": (po.get("terms") or {}).get("payment_terms_days"),
        "source_order": o["id"],
    }
    item = {
        "item_number": "00010",
        "material": cfg.get("material", ""),
        "short_text": (spec.get("part_name", "") + (f" {spec.get('drawing_ref')}" if spec.get("drawing_ref") else ""))[:40],
        "quantity": po["quantity"],
        "unit": cfg.get("unit", "PC"),
        "net_price": _rupees(po["unit_price_paise"] * price_unit),
        "price_unit": price_unit,
        "delivery_date": spec.get("needed_by", ""),
        "net_value": _rupees(po["total_paise"]),
    }
    return {
        "_mock": True,
        "_note": MOCK_NOTE,
        "_field_labels": {k: {"label": lbl, "sap_style_label_unverified": sap}
                          for k, lbl, sap in PO_HEADER_FIELDS + PO_ITEM_FIELDS},
        "header": header,
        "items": [item],
        "approvals": po.get("approvals", []),
        "audit_hash": po.get("audit_hash", ""),
        "pdf_sha256": po.get("sha256", ""),
    }


def po_csv(exp: dict[str, Any]) -> str:
    """One row per item, header fields repeated (the usual flat upload layout)."""
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    keys = [k for k, _, _ in PO_HEADER_FIELDS] + [k for k, _, _ in PO_ITEM_FIELDS]
    w.writerow(["# " + MOCK_NOTE])
    w.writerow(keys)
    w.writerow([f"{lbl} ({sap})" if sap else lbl for _, lbl, sap in PO_HEADER_FIELDS + PO_ITEM_FIELDS])
    for it in exp["items"]:
        row = exp["header"] | it
        w.writerow(["" if row[k] is None else row[k] for k in keys])
    return buf.getvalue()
